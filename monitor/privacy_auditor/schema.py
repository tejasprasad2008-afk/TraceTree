"""
Data models and schemas for the TraceTree Autonomous Privacy & Offline Verifier.
"""
from dataclasses import dataclass, field, asdict
from typing import List, Optional, Dict, Any, Tuple


@dataclass(frozen=True)
class UIElement:
    """Represents a discrete UI control from the Accessibility Tree or DOM."""
    id: str
    role: str
    title: str
    bounds: Tuple[float, float, float, float] = (0.0, 0.0, 0.0, 0.0)
    enabled: bool = True
    extra: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "role": self.role,
            "title": self.title,
            "bounds": list(self.bounds),
            "enabled": self.enabled,
            "extra": self.extra,
        }


@dataclass(frozen=True)
class Precondition:
    """Requirement that must be met in the active UI before executing a step."""
    expected_role: str
    expected_title: str

    def matches(self, element: UIElement) -> bool:
        """Check if a candidate element satisfies this precondition."""
        role_match = (
            self.expected_role.lower() in element.role.lower()
            or element.role.lower() in self.expected_role.lower()
        )
        title_match = (
            self.expected_title.lower() in element.title.lower()
            or element.title.lower() in self.expected_title.lower()
        )
        return role_match and title_match

    def to_dict(self) -> Dict[str, Any]:
        return {
            "expected_role": self.expected_role,
            "expected_title": self.expected_title,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Precondition":
        return cls(
            expected_role=str(data.get("expected_role", "")),
            expected_title=str(data.get("expected_title", "")),
        )


@dataclass(frozen=True)
class BatchStep:
    """A single speculative action within an AI-generated trajectory."""
    step: int
    action: str  # 'click', 'type', 'toggle', 'wait'
    target_id: str
    precondition: Precondition
    expected_outcome: str
    input_text: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "step": self.step,
            "action": self.action,
            "target_id": self.target_id,
            "precondition": self.precondition.to_dict(),
            "expected_outcome": self.expected_outcome,
            "input_text": self.input_text,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "BatchStep":
        precond_data = data.get("precondition", {})
        if isinstance(precond_data, dict):
            precond = Precondition.from_dict(precond_data)
        else:
            precond = Precondition(expected_role="", expected_title="")

        return cls(
            step=int(data.get("step", 1)),
            action=str(data.get("action", "click")).lower(),
            target_id=str(data.get("target_id", "")),
            precondition=precond,
            expected_outcome=str(data.get("expected_outcome", "")),
            input_text=data.get("input_text"),
        )


@dataclass(frozen=True)
class BatchPlan:
    """Multi-step action plan generated by the AI auditor."""
    thought_process: str
    batch_plan: List[BatchStep] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "thought_process": self.thought_process,
            "batch_plan": [s.to_dict() for s in self.batch_plan],
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "BatchPlan":
        steps_raw = data.get("batch_plan", [])
        steps = [BatchStep.from_dict(s) for s in steps_raw if isinstance(s, dict)]
        return cls(
            thought_process=str(data.get("thought_process", "")),
            batch_plan=steps,
        )


@dataclass(frozen=True)
class NetworkFlow:
    """Outbound socket or HTTP request recorded during the audit."""
    timestamp: float
    method: str
    url: str
    host: str
    path: str
    payload_size: int = 0
    associated_step_id: Optional[int] = None
    associated_action: Optional[str] = None
    category: str = "unknown"  # 'whitelisted_auth', 'telemetry', 'data_exfiltration', 'unknown'
    is_violation: bool = False
    detail: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "timestamp": self.timestamp,
            "method": self.method,
            "url": self.url,
            "host": self.host,
            "path": self.path,
            "payload_size": self.payload_size,
            "associated_step_id": self.associated_step_id,
            "associated_action": self.associated_action,
            "category": self.category,
            "is_violation": self.is_violation,
            "detail": self.detail,
        }


@dataclass(frozen=True)
class PrivacyReceipt:
    """Final Offline Truth Receipt validating or refuting privacy claims."""
    target_app: str
    bundle_id: Optional[str]
    timestamp: str
    audit_duration_seconds: float
    steps_executed: int
    replans_triggered: int
    total_outbound_requests: int
    violation_count: int
    verdict: str  # OFFLINE_VERIFIED | CONDITIONAL_AUTH_ONLY | PRIVACY_VIOLATION | INCONCLUSIVE
    violations: List[Dict[str, Any]] = field(default_factory=list)
    flows: List[Dict[str, Any]] = field(default_factory=list)
    diagnostic_note: Optional[str] = None
    schema: str = "tracetree.privacy_receipt.v1"

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
