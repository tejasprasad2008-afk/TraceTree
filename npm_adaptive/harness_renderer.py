"""Deterministically render validated plans into a trusted Node harness."""

from __future__ import annotations

import json
from typing import Any, Dict

from .models import HarnessPlan

_FIXTURE_VALUES: Dict[str, Any] = {
    "string-basic": "tracetree-synthetic-input",
    "string-empty": "",
    "number-zero": 0,
    "boolean-true": True,
    "json-empty-object": {},
    "json-empty-array": [],
    # This points only into the read-only synthetic profile supplied to the
    # container.  It is never a path from the analyst's machine.
    "developer-config-path": "/input/profile/home/.npmrc",
    "ci-event": {
        "action": "opened",
        "repository": {"full_name": "example-org/demo-repo"},
        "sender": {"login": "synthetic-user"},
    },
    "cloud-request": {"region": "us-tracetree-1", "request_id": "tt-synthetic-request"},
    "checkout-payload": {
        "event": "checkout_started",
        "customer_email": "synthetic-customer@example.invalid",
        "payment_token": "tt_payment_fixture",
    },
}


def render_harness(plan: HarnessPlan) -> str:
    """Render a bounded import/call harness from a validated plan.

    This renderer intentionally has no pathway for arbitrary planner-provided
    source.  All executable control flow lives in this trusted template.
    """

    serialised_plan = {
        "profile_id": plan.profile_id,
        "actions": [
            {
                "entrypoint": action.entrypoint,
                "loader": action.loader,
                "export_name": action.export_name,
                "fixture_ids": action.fixture_ids,
                "timeout_ms": action.timeout_ms,
            }
            for action in plan.actions
        ],
    }
    fixtures = {
        fixture_id: _FIXTURE_VALUES[fixture_id]
        for action in plan.actions
        for fixture_id in action.fixture_ids
    }
    return f"""// Generated by TraceTree from a validated HarnessPlan. Do not edit.
import {{ readFileSync }} from 'node:fs';
import {{ createRequire }} from 'node:module';
import {{ resolve, sep }} from 'node:path';
import {{ pathToFileURL }} from 'node:url';
import {{ takeCoverage }} from 'node:v8';

const require = createRequire(import.meta.url);
const plan = Object.freeze({json.dumps(serialised_plan, sort_keys=True)});
const fixtures = Object.freeze({json.dumps(fixtures, sort_keys=True)});
const packageRoot = resolve(process.env.TT_PACKAGE_DIR ?? '/input/package');
const entrypointsPath = process.env.TT_ENTRYPOINTS_PATH ?? '/input/entrypoints.json';
const entrypoints = JSON.parse(readFileSync(entrypointsPath, 'utf8')).entrypoints;
const modules = new Map();

function entrypointPath(entrypoint, loader) {{
  const configured = entrypoints.find((item) => item.specifier === entrypoint);
  const relative = configured?.[`${{loader}}_path`];
  if (typeof relative !== 'string' || relative.length === 0) {{
    throw new Error(`TRACE_TREE_UNRESOLVED_ENTRYPOINT:${{entrypoint}}:${{loader}}`);
  }}
  const absolute = resolve(packageRoot, relative);
  if (absolute === packageRoot || !absolute.startsWith(`${{packageRoot}}${{sep}}`)) {{
    throw new Error(`TRACE_TREE_UNSAFE_ENTRYPOINT:${{entrypoint}}`);
  }}
  return absolute;
}}

async function loadModule(entrypoint, loader) {{
  const cacheKey = `${{loader}}:${{entrypoint}}`;
  if (modules.has(cacheKey)) return modules.get(cacheKey);
  const sourcePath = entrypointPath(entrypoint, loader);
  const loaded = loader === 'require' ? require(sourcePath) : await import(pathToFileURL(sourcePath).href);
  modules.set(cacheKey, loaded);
  return loaded;
}}

async function callWithTimeout(target, args, timeoutMs) {{
  let timer;
  try {{
    return await Promise.race([
      Promise.resolve(target(...args)),
      new Promise((_, reject) => {{
        timer = setTimeout(() => reject(new Error('TRACE_TREE_ACTION_TIMEOUT')), timeoutMs);
      }}),
    ]);
  }} finally {{
    clearTimeout(timer);
  }}
}}

for (const [index, action] of plan.actions.entries()) {{
  const loaded = await loadModule(action.entrypoint, action.loader);
  const target = action.export_name === 'default' ? loaded.default : loaded[action.export_name];
  if (typeof target !== 'function') {{
    throw new Error(`TRACE_TREE_NON_CALLABLE_EXPORT:${{action.entrypoint}}:${{action.export_name}}`);
  }}
  const args = action.fixture_ids.map((fixtureId) => fixtures[fixtureId]);
  await callWithTimeout(target, args, action.timeout_ms);
  takeCoverage();
  process.stdout.write(JSON.stringify({{ event: 'action_complete', index }}) + '\\n');
}}
"""
